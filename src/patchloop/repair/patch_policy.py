"""Inspect patch effects with Git without touching the caller's index or worktree."""

from dataclasses import dataclass
from fnmatch import fnmatchcase
import os
from pathlib import Path
import shutil
import subprocess
from tempfile import NamedTemporaryFile, TemporaryDirectory
from typing import BinaryIO


class PatchPolicyError(ValueError):
    """The patch cannot be applied safely or violates its path policy."""


@dataclass(frozen=True)
class PatchInspection:
    tree_sha: str
    changed_paths: list[str]


_GIT_TIMEOUT = 30
_GIT_OPTIONS = (
    "-c", "core.hooksPath=" + os.devnull,
    "-c", "core.fsmonitor=false",
    "-c", "core.attributesFile=" + os.devnull,
    "-c", "core.autocrlf=false",
    "-c", "core.protectHFS=true",
    "-c", "core.protectNTFS=true",
    "-c", "diff.external=",
    "-c", "gc.auto=0",
    "-c", "maintenance.auto=false",
    "-c", "protocol.allow=never",
)


def _git_environment() -> dict[str, str]:
    # In particular, discard GIT_DIR, GIT_WORK_TREE, GIT_INDEX_FILE, object
    # overrides, injected config, tracing, and executable/transport overrides.
    env = {key: value for key, value in os.environ.items() if not key.upper().startswith("GIT_")}
    env.update(
        GIT_CONFIG_NOSYSTEM="1",
        GIT_CONFIG_SYSTEM=os.devnull,
        GIT_CONFIG_GLOBAL=os.devnull,
        GIT_ATTR_NOSYSTEM="1",
        GIT_NO_REPLACE_OBJECTS="1",
        GIT_NO_LAZY_FETCH="1",
        GIT_OPTIONAL_LOCKS="0",
        GIT_TERMINAL_PROMPT="0",
        LC_ALL="C",
    )
    return env


def _run_git(
    cwd: Path, env: dict[str, str], *args: str, input: bytes | None = None,
    stdin: BinaryIO | None = None, stdout: BinaryIO | int = subprocess.PIPE,
    config_options: tuple[str, ...] = (),
) -> bytes:
    try:
        result = subprocess.run(
            ["git", *_GIT_OPTIONS, *config_options, *args],
            cwd=cwd,
            env=env,
            input=input,
            stdin=stdin,
            stdout=stdout,
            stderr=subprocess.PIPE,
            timeout=_GIT_TIMEOUT,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise PatchPolicyError(f"git {args[0]} timed out") from exc
    except OSError as exc:
        raise PatchPolicyError(f"cannot run git {args[0]}: {exc}") from exc
    if result.returncode:
        detail = result.stderr[:2000].decode("utf-8", "replace").strip()
        raise PatchPolicyError(f"git {args[0]} failed: {detail}")
    return result.stdout or b""


def _git(
    cwd: Path, env: dict[str, str], *args: str, input: bytes | None = None,
    stdin: BinaryIO | None = None, stdout: BinaryIO | int = subprocess.PIPE,
) -> bytes:
    # Config enumeration does not read the index/worktree or run filters. Do
    # this before every operation, including nominally read-only commands such
    # as status, which can otherwise execute clean/process filters. Enumerate
    # names only; config values may contain credentials or arbitrary commands.
    keys = _run_git(cwd, env, "config", "--null", "--name-only", "--list", "--includes")
    options = []
    for key in keys.split(b"\0"):
        if key.startswith(b"filter.") and key.rsplit(b".", 1)[-1] in {b"clean", b"smudge", b"process", b"required"}:
            value = "false" if key.endswith(b".required") else ""
            options.extend(("-c", key.decode("utf-8", "surrogateescape") + "=" + value))
    return _run_git(cwd, env, *args, input=input, stdin=stdin, stdout=stdout, config_options=tuple(options))


def _quote_alternate(path: Path) -> str:
    # GIT_ALTERNATE_OBJECT_DIRECTORIES accepts C-quoted paths. Quote bytes so
    # colons, newlines, quotes, and non-UTF-8 names cannot split the path list.
    return '"' + "".join(f"\\{byte:03o}" for byte in os.fsencode(path)) + '"'


def _detach_objects(scratch: Path, env: dict[str, str], base_sha: str) -> dict[str, str]:
    # Git writes can refresh mtimes of *alternate* loose objects and packs.
    # Use the original alternates only for reads: pack the base commit and its
    # tree (not its history), then disconnect before any object-writing command.
    object_ids = _git(scratch, env, "rev-list", "--objects", "--no-object-names", f"{base_sha}^{{tree}}")
    detached = {key: value for key, value in env.items() if key != "GIT_ALTERNATE_OBJECT_DIRECTORIES"}
    with (scratch / "base.pack").open("w+b") as packed:
        _git(scratch, env, "pack-objects", "--stdout", input=base_sha.encode("ascii") + b"\n" + object_ids, stdout=packed)
        packed.seek(0)
        _git(scratch, detached, "index-pack", "--stdin", stdin=packed)
    return detached


def _publish_objects(source: Path, destination: Path, hash_length: int) -> None:
    # Only loose objects generated by apply/write-tree need publishing; the
    # temporary base pack already exists in the source repository. Atomic links
    # publish complete objects and never replace an existing/concurrent object.
    for fanout in source.iterdir():
        if len(fanout.name) != 2 or any(char not in "0123456789abcdef" for char in fanout.name):
            continue
        for obj in fanout.iterdir():
            if len(obj.name) != hash_length - 2 or any(char not in "0123456789abcdef" for char in obj.name):
                continue
            target = destination / fanout.name / obj.name
            if target.exists():
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with NamedTemporaryFile(prefix="tmp_obj_", dir=target.parent) as temporary:
                with obj.open("rb") as content:
                    shutil.copyfileobj(content, temporary)
                temporary.flush()
                os.chmod(temporary.name, 0o444)
                try:
                    os.link(temporary.name, target)
                except FileExistsError:
                    pass


def _check_path(path: str, allowed: tuple[str, ...], protected: tuple[str, ...]) -> None:
    parts = path.split("/")
    if any(part in {"", ".", ".."} for part in parts):
        raise PatchPolicyError(f"unsafe patch path: {path!r}")
    if any(part.casefold() in {".git", ".gitattributes", ".gitmodules"} for part in parts):
        raise PatchPolicyError(f"Git control path is forbidden: {path!r}")
    if any(fnmatchcase(path, pattern) for pattern in protected):
        raise PatchPolicyError(f"path protected: {path!r}")
    if allowed and not any(fnmatchcase(path, pattern) for pattern in allowed):
        raise PatchPolicyError(f"path outside allowed_paths: {path!r}")


def _changed_paths(raw: bytes, allowed: tuple[str, ...], protected: tuple[str, ...]) -> list[str]:
    if not raw:
        raise PatchPolicyError("patch makes no changes")
    fields = raw.split(b"\0")
    if fields.pop() != b"" or len(fields) % 2:
        raise PatchPolicyError("invalid Git raw diff")
    paths = []
    # --no-renames represents renames as deletion + addition, so both ends
    # pass through the same policy (including pure renames and copies).
    for header, encoded_path in zip(fields[::2], fields[1::2]):
        metadata = header.split()
        if len(metadata) != 5 or not metadata[0].startswith(b":") or metadata[4] not in {b"A", b"D", b"M", b"T"}:
            raise PatchPolicyError("invalid Git raw diff record")
        path = encoded_path.decode("utf-8", "surrogateescape")
        _check_path(path, allowed, protected)
        old_mode, new_mode = metadata[0][1:], metadata[1]
        if old_mode not in {b"000000", b"100644", b"100755"} or new_mode not in {b"000000", b"100644", b"100755"}:
            raise PatchPolicyError(f"symlink, gitlink, or unsupported mode at path: {path!r}")
        paths.append(path)
    return paths


def inspect_patch(
    repo_path: Path,
    base_sha: str,
    patch: bytes,
    *,
    allowed_paths: tuple[str, ...] = (),
    protected_paths: tuple[str, ...] = (),
    write_objects: bool = False,
) -> PatchInspection:
    """Apply to a temporary index and check actual paths/modes relative to base.

    Patterns use fnmatchcase on repository-relative POSIX paths (``*`` also
    matches ``/``); an empty allowlist allows any non-protected regular file.
    The base must be a full SHA-1/SHA-256 commit ID. Dirty, staged, and untracked
    worktree contents have no bearing on the inspection.

    By default new objects exist only during this call: the returned tree ID
    need not be resolvable afterward. With write_objects=True, new objects are
    published after policy checks, and the tree ID can be passed to commit-tree.
    Neither mode changes existing objects, the source index, worktree, refs, or
    configuration. The base tree is packed temporarily to isolate even Git's
    object-mtime refreshes; its history is not copied.
    """
    if not isinstance(base_sha, str) or len(base_sha) not in {40, 64} or any(
        char not in "0123456789abcdefABCDEF" for char in base_sha
    ):
        raise PatchPolicyError("base_sha must be a full 40- or 64-digit hexadecimal commit ID")
    if not isinstance(patch, bytes) or not patch.strip():
        raise PatchPolicyError("empty patch (expected nonempty bytes)")

    env = _git_environment()
    try:
        repo_path = Path(repo_path).resolve()
        objects = Path(os.fsdecode(_git(repo_path, env, "rev-parse", "--path-format=absolute", "--git-path", "objects").removesuffix(b"\n")))
        object_format = _git(repo_path, env, "rev-parse", "--show-object-format=storage").strip().decode("ascii")
        if object_format not in {"sha1", "sha256"}:
            raise PatchPolicyError("unsupported Git object format")

        with TemporaryDirectory(prefix="patch-policy-") as directory:
            scratch = Path(directory)
            git_dir = scratch / "repo.git"
            _git(scratch, env, "init", "--bare", "--template=", f"--object-format={object_format}", str(git_dir))
            isolated = {
                **env,
                "GIT_DIR": str(git_dir),
                "GIT_INDEX_FILE": str(scratch / "index"),
                "GIT_OBJECT_DIRECTORY": str(git_dir / "objects"),
                "GIT_ALTERNATE_OBJECT_DIRECTORIES": _quote_alternate(objects),
            }
            if _git(scratch, isolated, "cat-file", "-t", base_sha).strip() != b"commit":
                raise PatchPolicyError("base_sha must identify a commit")
            isolated = _detach_objects(scratch, isolated, base_sha)
            _git(scratch, isolated, "read-tree", base_sha)
            _git(scratch, isolated, "apply", "--cached", "--binary", "--whitespace=nowarn", "-", input=patch)
            raw = _git(
                scratch, isolated, "diff", "--cached", "--raw", "-z", "--no-renames",
                "--no-ext-diff", "--no-textconv", "--no-abbrev", "--ignore-submodules=none",
                base_sha, "--",
            )
            paths = _changed_paths(raw, allowed_paths, protected_paths)
            tree_sha = _git(scratch, isolated, "write-tree").strip().decode("ascii")
            if write_objects:
                _publish_objects(git_dir / "objects", objects, len(tree_sha))
            return PatchInspection(tree_sha=tree_sha, changed_paths=paths)
    except OSError as exc:
        raise PatchPolicyError(f"cannot inspect patch: {exc}") from exc
